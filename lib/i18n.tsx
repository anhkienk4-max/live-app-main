function interpolate(value: string, variables?: Variables) {
  if (!variables) return value
  return Object.entries(variables).reduce(
    (result, [key, replacement]) => result.replaceAll(`{${key}}`, String(replacement)),
    value,
  )
}

function translateLegacyValue(value: string, language: Language) {
  const exact = language === 'vi'
    ? englishToVietnamese.get(value) || legacyVietnamese[value]
    : vietnameseToEnglish.get(value) ||
      Object.entries(legacyVietnamese).find(([, vietnamese]) => vietnamese === value)?.[0]
  if (exact) return exact
  const dynamic = dynamicLegacyPatterns.find(pattern => value.match(language === 'vi' ? pattern.en : pattern.vi))
  if (dynamic) {
    const match = value.match(language === 'vi' ? dynamic.en : dynamic.vi)
    if (match) return language === 'vi' ? dynamic.toVi(match) : dynamic.toEn(match)
  }
  return value
}

type Context = {
  language: Language
  setLanguage: (language: Language) => void
  t: (key: TranslationKey, variables?: Variables) => string
  translate: (value: string) => string
}

const LanguageContext = React.createContext<Context | null>(null)

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = React.useState<Language>('en')
  React.useEffect(() => {
    const saved = window.localStorage.getItem('livestream-ops-language')
    if (saved === 'en' || saved === 'vi') setLanguageState(saved)
  }, [])
  const setLanguage = React.useCallback((next: Language) => {
    setLanguageState(next)
    window.localStorage.setItem('livestream-ops-language', next)
  }, [])
  React.useEffect(() => {
    document.documentElement.lang = language
    const apply = (root: Node) => {
      const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT)
      const nodes: Text[] = []
      let node: Node | null
      while ((node = walker.nextNode())) nodes.push(node as Text)
      nodes.forEach(text => {
        const trimmed = text.nodeValue?.trim()
        if (!trimmed) return
        const translated = translateLegacyValue(trimmed, language)
        if (translated !== trimmed) text.nodeValue = text.nodeValue?.replace(trimmed, translated) ?? translated
      })
      if (root instanceof Element) {
        ;[root, ...root.querySelectorAll('*')].forEach(element =>
          ['placeholder', 'title', 'aria-label'].forEach(attribute => {
            const value = element.getAttribute(attribute)
            if (value) {
              const translated = translateLegacyValue(value, language)
              if (translated !== value) element.setAttribute(attribute, translated)
            }
          })
        )
      }
    }
    apply(document.body)
    const observer = new MutationObserver(records => records.forEach(record => {
      if (record.type === 'characterData' || record.type === 'attributes') apply(record.target)
      else record.addedNodes.forEach(apply)
    }))
    observer.observe(document.body, {
      attributes: true,
      attributeFilter: ['placeholder', 'title', 'aria-label'],
      characterData: true,
      childList: true,
      subtree: true,
    })
    return () => observer.disconnect()
  }, [language])
  const value = React.useMemo<Context>(() => ({
    language,
    setLanguage,
    t: (key, variables) => interpolate(dictionary[language][key], variables),
    translate: value => translateLegacyValue(value, language),
  }), [language, setLanguage])
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useTranslation() {
  const context = React.useContext(LanguageContext)
  if (!context) throw new Error('useTranslation must be used inside LanguageProvider')
  return context
}

export function LocalizedPageHeading({ title, subtitle }: { title: TranslationKey; subtitle?: TranslationKey }) {
  const { t } = useTranslation()
  return <div><h1 className="mb-2 text-3xl font-bold text-gray-900">{t(title)}</h1>{subtitle && <p className="text-gray-600">{t(subtitle)}</p>}</div>
}
