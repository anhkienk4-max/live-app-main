CREATE TABLE IF NOT EXISTS public.rc19_leader_brand_scopes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  leader_business_user_id text NOT NULL REFERENCES public.business_users(id) ON DELETE RESTRICT,
  brand_id text NOT NULL REFERENCES public.brands(id) ON DELETE RESTRICT,
  scope_key text NOT NULL CHECK (scope_key IN (
    'shifts.read', 'shifts.manage', 'staff.read', 'staff.manage', 'workforce.read',
    'reports.read', 'reports.submit', 'reports.review', 'reports.export'
  )),
  status text NOT NULL CHECK (status IN ('active', 'revoked')),
  valid_from timestamptz NOT NULL,
  valid_until timestamptz,
  revoked_at timestamptz,
  version integer NOT NULL CHECK (version > 0),
  granted_by text NOT NULL REFERENCES public.business_users(id) ON DELETE RESTRICT,
  updated_by text NOT NULL REFERENCES public.business_users(id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
  updated_at timestamptz NOT NULL DEFAULT statement_timestamp(),
  CONSTRAINT rc19_leader_brand_scope_window_check CHECK (valid_until IS NULL OR valid_until > valid_from),
  CONSTRAINT rc19_leader_brand_scope_status_check CHECK (
    (status = 'active' AND revoked_at IS NULL) OR (status = 'revoked' AND revoked_at IS NOT NULL)
  ),
  CONSTRAINT rc19_leader_brand_scope_identity_key UNIQUE (leader_business_user_id, brand_id, scope_key)
);

CREATE INDEX IF NOT EXISTS rc19_leader_brand_scope_effective_idx
  ON public.rc19_leader_brand_scopes (leader_business_user_id, scope_key, brand_id)
  WHERE status = 'active';

CREATE TABLE IF NOT EXISTS public.rc19_leader_brand_scope_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scope_id bigint NOT NULL REFERENCES public.rc19_leader_brand_scopes(id) ON DELETE RESTRICT,
  leader_business_user_id text NOT NULL REFERENCES public.business_users(id) ON DELETE RESTRICT,
  brand_id text NOT NULL REFERENCES public.brands(id) ON DELETE RESTRICT,
  scope_key text NOT NULL,
  event_type text NOT NULL CHECK (event_type IN ('grant', 'update', 'revoke', 'automatic_revoke')),
  prior_status text CHECK (prior_status IS NULL OR prior_status IN ('active', 'revoked')),
  new_status text NOT NULL CHECK (new_status IN ('active', 'revoked')),
  version integer NOT NULL CHECK (version > 0),
  actor_business_user_id text REFERENCES public.business_users(id) ON DELETE SET NULL,
  reason text NOT NULL,
  occurred_at timestamptz NOT NULL DEFAULT statement_timestamp()
);

CREATE INDEX IF NOT EXISTS rc19_leader_brand_scope_events_subject_idx
  ON public.rc19_leader_brand_scope_events (leader_business_user_id, occurred_at DESC);

ALTER TABLE public.rc19_leader_brand_scopes ENABLE ROW LEVEL SECURITY;
