  FOR SELECT TO authenticated
  USING (
    private.current_business_user_is_active()
    AND status = 'active' AND account_status = 'active'
    AND archived_at IS NULL AND deleted_at IS NULL
    AND (
      private.current_system_permission() = 'admin'
      OR id = private.current_business_user_id()
      OR (private.current_system_permission() = 'leader' AND EXISTS (
        SELECT 1 FROM public.shifts AS shift
        WHERE shift.deleted_at IS NULL AND shift.archived_at IS NULL
          AND private.rc19_has_any_leader_brand_scope(shift.brand_id,
            ARRAY['shifts.read', 'shifts.manage', 'staff.read', 'staff.manage', 'workforce.read']::text[])
          AND (
            business_users.id IN (shift.host_id, shift.support_id, shift.technical_id)
            OR EXISTS (
              SELECT 1 FROM public.shift_registrations AS registration
              WHERE registration.shift_id = shift.id AND registration.user_id = business_users.id
                AND registration.status IN ('pending', 'approved', 'manually_assigned')
            )
          )
      ))
    )
  );

