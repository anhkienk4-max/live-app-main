async function setupBaseSchema(db: PGlite) {
  await db.exec(`
    do $$
    begin
      if not exists (select 1 from pg_roles where rolname = 'anon') then
        create role anon;
      end if;
      if not exists (select 1 from pg_roles where rolname = 'authenticated') then
        create role authenticated;
      end if;
      if not exists (select 1 from pg_roles where rolname = 'service_role') then
        create role service_role;
      end if;
    end
    $$;

    create schema if not exists private;
    create schema if not exists auth;
    grant usage on schema private to authenticated;

    create or replace function auth.uid() returns uuid as $$
      select null::uuid;
    $$ language sql stable;

    create table if not exists public.business_users (
      id text primary key,
      full_name text not null,
      role text default 'staff',
      status text default 'active',
      account_status text default 'active',
      system_permission text not null default 'member',
      operational_roles text[] default '{}',
      archived_at timestamptz,
      deleted_at timestamptz
    );

    create table if not exists public.brands (
      id text primary key,
      name text not null,
      status text default 'active',
      archived_at timestamptz,
      deleted_at timestamptz
    );

    create table if not exists public.platforms (
      id text primary key,
      name text not null
    );

    create table if not exists public.shifts (
      id text primary key default gen_random_uuid()::text,
      date date not null,
      start_time time not null,
      end_time time not null,
      start_at timestamptz,
      end_at timestamptz not null,
      timezone text default 'Asia/Ho_Chi_Minh',
      brand_id text references public.brands(id),
      platform_id text references public.platforms(id),
      campaign_id text,
      title text,
      studio text,
      host_id text,
      support_id text,
      technical_id text,
      required_host_count smallint default 1,
      required_support_count smallint default 1,
      required_technical_count smallint default 0,
      registration_locked boolean default false,
      registration_cutoff_at timestamptz,
      allow_multi_role boolean default false,
      status text default 'scheduled',
      product_notes text,
      deleted_at timestamptz,
      archived_at timestamptz
    );

    create or replace function public.get_shift_staffing_summary(p_shift_ids text[])
    returns table(shift_id text, role text, required int, approved int) as $$
      select s.id, 'host'::text, s.required_host_count::int, 0::int from public.shifts s where s.id = any(p_shift_ids);
    $$ language sql stable;

    create table if not exists public.shift_registrations (
      id text primary key default gen_random_uuid()::text,
      shift_id text not null references public.shifts(id) on delete cascade,
      user_id text not null references public.business_users(id),
      operational_role text not null,
      status text not null check (status in ('pending', 'approved', 'manually_assigned', 'cancelled', 'rejected')),
      imported_name text,
      source text default 'self_registration'
    );

    create table if not exists public.rc19_leader_brand_scopes (
      id bigint generated by default as identity primary key,
      leader_business_user_id text not null references public.business_users(id),
      brand_id text not null references public.brands(id),
      scope_key text not null,
      status text not null check (status in ('active', 'revoked')),
      valid_from timestamptz not null default statement_timestamp(),
      valid_until timestamptz,
      revoked_at timestamptz,
      version integer not null default 1,
      granted_by text not null references public.business_users(id),
      updated_by text not null references public.business_users(id),
      created_at timestamptz not null default statement_timestamp(),
      updated_at timestamptz not null default statement_timestamp()
    );

    create table if not exists private.active_session (
      user_id text,
      system_permission text default 'member'
    );

    create or replace function private.current_business_user_id() returns text as $$
      select user_id from private.active_session limit 1;
    $$ language sql stable;

    create or replace function private.current_system_permission() returns text as $$
      select coalesce((select system_permission from private.active_session limit 1), 'member');
    $$ language sql stable;

    create or replace function private.current_business_user_is_active() returns boolean as $$
      select exists (
        select 1 from public.business_users u
        where u.id = private.current_business_user_id()
          and u.status = 'active' and u.account_status = 'active'
          and u.archived_at is null and u.deleted_at is null
      );
    $$ language sql stable;

    create or replace function private.require_shift_actor(req boolean) returns text as $$
      select private.current_business_user_id();
    $$ language sql stable;

    create or replace function private.rc19_has_any_leader_brand_scope(p_brand_id text, p_scope_keys text[])
    returns boolean as $$
      select coalesce((
        select private.current_business_user_is_active()
          and private.current_system_permission() = 'leader'
          and exists (
            select 1
            from public.rc19_leader_brand_scopes as scope_row
            join public.brands as brand on brand.id = scope_row.brand_id
            where scope_row.leader_business_user_id = private.current_business_user_id()
              and scope_row.brand_id = p_brand_id
              and scope_row.scope_key = any(p_scope_keys)
              and scope_row.status = 'active'
              and scope_row.valid_from <= statement_timestamp()
              and (scope_row.valid_until is null or statement_timestamp() < scope_row.valid_until)
              and brand.status = 'active'
              and brand.archived_at is null
              and brand.deleted_at is null
          )
      ), false);
    $$ language sql stable;
  `)
}

async function setActor(db: PGlite, userId: string, permission: 'admin' | 'leader' | 'member') {
  await db.exec(`
    delete from private.active_session;
    insert into private.active_session (user_id, system_permission) values ('${userId}', '${permission}');
  `)
}

